"""Static catalogue handed to the web (fields, presets, patterns, factors, playbooks, exit variants).

Why: the UI must show the SAME field ids, units and rule texts the backend validates (single source of truth = this Python
code). ``apps/web/src/pages/ext/b/catalog.json`` is generated by ``python -m pulse.domain.screening.export`` and a test fails
when the file drifts from the code. Invariants: pure data, no IO beyond the optional file write of ``main``.
"""
from __future__ import annotations

import json
import sys
from pathlib import Path

from ..playbooks import exits as EX
from ..playbooks import library as L
from ..playbooks.spec import FAMILIES
from . import catalog as K
from . import factor_lab as FL
from . import patterns as P
from . import presets as PR


def build() -> dict:
    return {
        "catalog_version": K.CATALOG_VERSION,
        "field_version": K.FIELD_VERSION,
        "subject_id": K.SUBJECT_ID,
        "fields": [{"id": f.id, "label": f.label, "unit": f.unit, "description": f.description, "group": f.group, "needs": f.needs} for f in K.FIELDS],
        "unsupported_terms": list(K.UNSUPPORTED),
        "presets": [{"id": p.id, "name": p.name, "subtitle": p.subtitle, "text": p.text, "note": p.note} for p in PR.PRESETS],
        "patterns": [{"id": d.id, "name": d.name, "family": d.family, "rule": d.rule, "omitted": d.omitted, "min_bars": d.min_bars} for d in P.DEFINITIONS],
        "factors": [{"id": f.id, "name": f.name, "description": f.description} for f in FL.FACTORS],
        "families": FAMILIES,
        "playbooks": [{"id": p.id, "name": p.name, "family": p.family, "style": p.style, "horizon": p.horizon, "rule": p.rule, "source": p.source,
                       "requires": list(p.requires), "unavailable_reason": p.unavailable_reason, "holding_days": p.exits.holding_days,
                       "stop_loss_pct": p.exits.stop_loss_pct, "trailing_stop_pct": p.exits.trailing_stop_pct, "max_positions": p.max_positions,
                       "params": [{"key": x.key, "label": x.label, "value": x.value} for x in p.params]} for p in (L.REGISTRY[i] for i in L.ORDER)],
        "exit_variants": [{"key": k, "label": label} for k, label, _ in EX.VARIANTS],
    }


def render() -> str:
    return json.dumps(build(), ensure_ascii=False, indent=1, sort_keys=True) + "\n"


def main() -> None:
    target = Path(sys.argv[1]) if len(sys.argv) > 1 else Path("apps/web/src/pages/ext/b/catalog.json")
    target.parent.mkdir(parents=True, exist_ok=True)
    target.write_text(render(), encoding="utf-8", newline="\n")


if __name__ == "__main__":
    main()
