"""Generate serialized TypeScript models from Pydantic JSON Schema, without Node tools."""
from __future__ import annotations

import argparse
import json
from pathlib import Path

from contracts import schema

ROOT = Path(__file__).resolve().parents[1]


def ts_type(node: dict) -> str:
    if "$ref" in node:
        return node["$ref"].rsplit("/", 1)[-1]
    if "const" in node:
        return json.dumps(node["const"], ensure_ascii=False)
    if "enum" in node:
        return " | ".join(json.dumps(value, ensure_ascii=False) for value in node["enum"])
    if "anyOf" in node:
        return " | ".join(ts_type(item) for item in node["anyOf"])
    kind = node.get("type")
    if kind == "array":
        return f"Array<{ts_type(node['items'])}>"
    if kind == "object":
        extra = node.get("additionalProperties", {})
        return f"Record<string, {ts_type(extra) if isinstance(extra, dict) else 'unknown'}>"
    return {"string": "string", "number": "number", "integer": "number", "boolean": "boolean", "null": "null"}.get(kind, "unknown")


def render() -> str:
    definitions: dict[str, dict] = {}
    for name, value in vars(schema).items():
        if isinstance(value, type) and issubclass(value, schema.Contract) and value is not schema.Contract:
            document = value.model_json_schema(mode="serialization")
            definitions.update(document.pop("$defs", {}))
            definitions[name] = document
    lines = ["// Generated by python -m contracts.generate_types. DO NOT EDIT.",
             "// Response properties are serialized explicitly. Use Partial<T> for defaulted request inputs.", ""]
    for name, node in sorted(definitions.items()):
        if "enum" in node:
            lines += [f"export type {name} = {ts_type(node)};", ""]
            continue
        lines.append(f"export interface {name} {{")
        for key, prop in node.get("properties", {}).items():
            lines.append(f"  {key}: {ts_type(prop)};")
        lines += ["}", ""]
    for name, value in [("DEFAULT_FILTER", schema.ScreenerFilterRequest()), ("DEFAULT_BACKTEST", schema.BacktestRequest()), ("DEFAULT_FACTOR_LAB", schema.FactorLabRequest())]:
        lines += [f"export const {name}: {type(value).__name__} = " + value.model_dump_json(indent=2) + ";", ""]
    return "\n".join(lines)


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    target = ROOT / "frontend/src/core/contract.ts"
    content = render()
    if args.check:
        if not target.exists() or target.read_text(encoding="utf-8") != content:
            raise SystemExit("Contract drift: run python -m contracts.generate_types")
        print("Generated contract is current")
    else:
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_text(content, encoding="utf-8", newline="\n")
        print(f"Generated {target}")


if __name__ == "__main__":
    main()
